SORTED_CITY_ALIASES: Final[tuple[tuple[str, str], ...]] = tuple(
    sorted(CITY_ALIASES.items(), key=lambda item: len(item[0]), reverse=True)
)


def normalize_province(province: str | None) -> str:
    """移除省级行政区后缀，返回项目统一使用的省份简称。"""

    value = re.sub(r"\s+", "", str(province or ""))
    value = re.sub(
        r"(?:壮族自治区|回族自治区|维吾尔自治区|自治区|特别行政区|省|市)$",
        "",
        value,
    )
    aliases = {"内蒙": "内蒙古", "广西壮族": "广西", "宁夏回族": "宁夏", "新疆维吾尔": "新疆"}
    return aliases.get(value, value)


def find_city(raw_city: str | None) -> tuple[str, str | None, str | None, str | None]:
    """从混合城市字段提取标准城市、区县、省份和城市等级。"""

    raw = str(raw_city or "").strip()
    if not raw:
        return "", None, None, None
    compact = re.sub(r"\s+", "", raw.replace("・", "·").replace("•", "·"))
    # 只移除普通省/自治区前缀；北京、上海、天津、重庆必须保留为城市参与匹配。
    compact = re.sub(
        r"^(?:[^·/]{2,8}省|[^·/]{2,12}自治区)[·/,-]*", "", compact
    )

    for alias, standard in SORTED_CITY_ALIASES:
        position = compact.find(alias)
        if position < 0:
            continue
        info = CITY_PROVINCE_MAP[standard]
        remainder = compact[position + len(alias):]
        remainder = re.sub(r"^[·/|,，:：-]+", "", remainder).strip()
        district = remainder or None
        return standard, district, info["province"], info["level"]

    # 未收录城市仍按“XX市”规则保底，不臆测省份和等级。
    first_part = re.split(r"[·・•/|,，\s]+", raw, maxsplit=1)[0].strip()
    fallback = re.sub(r"(?:市|地区|盟|自治州)$", "", first_part)
    return fallback, None, None, "其他"


def city_count() -> int:
    """返回映射表覆盖的标准地级行政区数量，供测试和运维检查使用。"""

    return len(CITY_PROVINCE_MAP)
