def _city_level(city: str) -> str:
    """根据显式城市等级集合返回分类，未列出的城市统一记为其他。"""

    if city in FIRST_TIER:
        return "一线"
    if city in NEW_FIRST_TIER:
        return "新一线"
    if city in SECOND_TIER:
        return "二线"
    if city in THIRD_TIER:
        return "三线"
    return "其他"


